/** Land dots as [longitude, latitude] in degrees. */
export function landDots(): [number, number][] {
  const bin = atob(DATA);
  const dots: [number, number][] = [];
  let cell = 0;
  ROW_COUNTS.forEach((n, r) => {
    const lat = LAT_MAX - r * LAT_STEP;
    for (let k = 0; k < n; k++, cell++) {
      if ((bin.charCodeAt(cell >> 3) >> (cell & 7)) & 1) dots.push([-180 + ((k + 0.5) * 360) / n, lat]);
    }
  });
  return dots;
}
